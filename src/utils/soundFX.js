// Created: 2026-07-31

let audioCtx = null;
let isMuted = localStorage.getItem('build_55_sound_muted') === 'true';

/**
 * Initializes or returns the active WebAudio AudioContext instance.
 * @returns {AudioContext|null} Web Audio API context.
 */
function getAudioContext() {
  if (typeof window === 'undefined') return null;
  if (!audioCtx) {
    const AudioContextClass = window.AudioContext || window.webkitAudioContext;
    if (AudioContextClass) {
      audioCtx = new AudioContextClass();
    }
  }
  if (audioCtx && audioCtx.state === 'suspended') {
    audioCtx.resume();
  }
  return audioCtx;
}

/**
 * Checks whether sound effects are currently muted.
 * @returns {boolean} True if muted.
 */
export function getSoundMutedState() {
  return isMuted;
}

/**
 * Toggles global audio sound effects mute state.
 * @returns {boolean} New mute state.
 */
export function toggleSoundMuteState() {
  isMuted = !isMuted;
  localStorage.setItem('build_55_sound_muted', isMuted ? 'true' : 'false');
  return isMuted;
}

/**
 * Plays a synthesized UI click sound (short high chime).
 */
export function playClickSound() {
  if (isMuted) return;
  const ctx = getAudioContext();
  if (!ctx) return;

  try {
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    osc.type = 'sine';
    osc.frequency.setValueAtTime(800, ctx.currentTime);
    osc.frequency.exponentialRampToValueAtTime(400, ctx.currentTime + 0.05);

    gain.gain.setValueAtTime(0.08, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 0.05);

    osc.connect(gain);
    gain.connect(ctx.destination);

    osc.start();
    osc.stop(ctx.currentTime + 0.05);
  } catch (e) {
    // Ignore audio context errors gracefully
  }
}

